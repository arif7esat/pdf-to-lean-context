def kp():
    """Gömülü kitap_paketle modülü (şekil bulma/kırpma kodunun TEK kaynağı)."""
    global _kp
    if _kp is None:
        kod = zlib.decompress(base64.b64decode("".join(KP_KODU.split()))).decode("utf-8")
        m = types.ModuleType("kitap_paketle")
        m.__file__ = "kitap_paketle.py"
